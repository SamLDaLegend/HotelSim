/**
 * v7 -> v8: a world whose stays ended for reasons nobody wrote down (G-015).
 *
 * ADR-0006 fires for the seventh time. `World.guestOutcomes` changes SHAPE rather than
 * gaining a sibling field, and that owes a migration for the same reason a new field does:
 * without one, the same old bytes quietly mean something new. The permanent v1 fixture now
 * walks 1 -> 2 -> 3 -> 4 -> 5 -> 6 -> 7 -> 8, migrated and never regenerated.
 *
 * WHAT EACH v7 COUNTER MEANS IN v8, ARGUED FROM THE ERA AND NOT FROM CONVENIENCE:
 *
 *   arrived      unchanged. It was never an outcome; it is the left-hand side of the law.
 *   satisfied -> satisfied. The same event under the same name.
 *   unsatisfied -> gaveUpWaiting. NOT A RENAME MADE UP HERE: v7's own field documented
 *                itself as "patience for a room ran out before one was free", which is
 *                that reason stated as a reason. Nothing is lost and nothing is invented.
 *   evicted   -> evictedCauseUnrecorded, AND THIS IS THE POINT OF THE WHOLE STEP. v8
 *                distinguishes "the room was demolished" from "the room is still standing
 *                and stopped being a room". A v7 world recorded neither — it counted the
 *                event and threw the cause away — so mapping these to either live reason
 *                would state as fact something these bytes do not say. Both causes really
 *                occurred in the v7 era (`validity.guest.test.ts` drives one of each), so
 *                there is not even a majority to appeal to. The honest v8 value is a row
 *                that means *an eviction from before causes were recorded*, and the tick
 *                can never write it (`TickDepartureReason` excludes it).
 *
 * Reads no content and no live constant, so the same v7 bytes produce the same v8 world
 * however the shipped reason list changes afterwards (ADR-0008).
 *
 * NOT TESTED BY THE FIXTURE ALONE, DELIBERATELY. The permanent v1 fixture reaches this step
 * with three zero counters, over which any mapping whatsoever would look correct — ADR-0007's
 * exact shape. `outcome.save.test.ts` drives a synthetic v7 world with all three counters
 * distinct and non-zero and watches each one land in its own row.
 */
function migrateV7ToV8(world: unknown): unknown {
  if (!isRecord(world)) {
    throw new Error('Save is corrupt: world is not an object');
  }
  const outcomes = world['guestOutcomes'];
  if (!isRecord(outcomes)) {
    throw new Error('Save is corrupt: world.guestOutcomes is missing, so its stays cannot be given reasons');
  }
  // The one way this step could destroy data — spreading over a table somebody already
  // has — is the one thing it refuses to do, exactly as all six earlier steps refuse.
  // `Object.keys().includes` rather than `in`, because `JSON.parse` makes `__proto__` an
  // own key (G-003).
  if (Object.keys(outcomes).includes('departures')) {
    throw new Error(
      'world.guestOutcomes already has a "departures" field, so it is not a v7 world; migrating it would overwrite a real table',
    );
  }
  const counters: Record<string, number> = {};
  for (const key of ['arrived', 'satisfied', 'unsatisfied', 'evicted'] as const) {
    const value = outcomes[key];
    if (typeof value !== 'number') {
      throw new Error(
        `Save is corrupt: world.guestOutcomes.${key} is missing or not a number, so this world's stays cannot be counted`,
      );
    }
    counters[key] = value;
  }
  // Mapped by POSITION IN THE FROZEN LITERAL, so the shape of a migrated v7 world is this
  // constant's and the values are the bytes'.
  const carried: Record<string, number> = {
    satisfied: counters['satisfied'] ?? 0,
    gaveUpWaiting: counters['unsatisfied'] ?? 0,
    evictedCauseUnrecorded: counters['evicted'] ?? 0,
  };
  return {
    ...world,
    guestOutcomes: {
      arrived: counters['arrived'] ?? 0,
      departures: V8_MIGRATION_GUEST_OUTCOMES.map((row) => ({
        reason: row.reason,
        count: carried[row.reason] ?? row.count,
      })),
    },
  };
}

/**
 * v8 -> v9: a world whose guests could not change their minds (G-014b).
 *
 * ADR-0006 fires for the eighth time. Two fields arrive in one step and BOTH defaults are
 * argued from the era rather than chosen (ADR-0008) — `ai-critic` named the second one at
 * PLAN, because a migration that only defaults the field you were thinking about is how a
 * save quietly means something new:
 *
 *   guests[].needs[].abandonCount = 0   In the v8 era `reserve` returned early for any
 *                                       engaged guest, so no guest could abandon an
 *                                       engagement at all. Every instance of the count these
 *                                       bytes describe IS zero. Exactly true, not a guess.
 *   needOutcomes[].abandoned      = 0   The same fact one fold downstream: a tally row in a
 *                                       v8 world was accumulated from need vectors that had
 *                                       no abandonment to contribute.
 *
 * Reads no content and no live constant, so the same v8 bytes produce the same v9 world
 * however the shipped margin changes afterwards (ADR-0008). In particular it does NOT
 * consult `abandonMarginOf`: the margin is a fact about the content a world is run under and
 * not about the bytes, and a migration that read it would make an old save's meaning depend
 * on today's `guest-rules.json`.
 *
 * NOT TESTED BY THE FIXTURE ALONE, DELIBERATELY. The permanent v1 fixture carries no guests
 * and no tally rows, so this step would run over two empty arrays and prove nothing —
 * ADR-0007's exact shape, and the reason `migrateV6ToV7` and `migrateV7ToV8` both carry this
 * paragraph. `needs.hysteresis.save.test.ts` drives a synthetic v8 world with a met need, a
 * pending need and a populated tally and watches both zeroes land.
 */
function migrateV8ToV9(world: unknown): unknown {
  if (!isRecord(world)) {
    throw new Error('Save is corrupt: world is not an object');
  }
  const guests = world['guests'];
  if (!isRecord(guests)) {
    throw new Error('Save is corrupt: world.guests is missing, so its needs cannot carry an abandonment count');
  }
  const list = guests['list'];
  if (!Array.isArray(list)) {
    throw new Error('Save is corrupt: world.guests.list is missing or not an array');
  }
  const counted: unknown[] = list.map((guest, index) => {
    if (!isRecord(guest)) {
      throw new Error(`Save is corrupt: world.guests.list[${index}] is not an object`);
    }
    const needs = guest['needs'];
    if (!Array.isArray(needs)) {
      throw new Error(`Save is corrupt: world.guests.list[${index}].needs is missing or not an array`);
    }
    return {
      ...guest,
      needs: needs.map((need, at) => {
        if (!isRecord(need)) {
          throw new Error(`Save is corrupt: world.guests.list[${index}].needs[${at}] is not an object`);
        }
        // The one way this step could destroy data — overwriting a count somebody already
        // made — is the one thing it refuses to do, exactly as all seven earlier steps
        // refuse. `Object.keys().includes` rather than `in`, because `JSON.parse` makes
        // `__proto__` an own key (G-003).
        if (Object.keys(need).includes('abandonCount')) {
          throw new Error(
            `world.guests.list[${index}].needs[${at}] already has an "abandonCount" field, so it is not a v8 need; migrating it would overwrite a real count`,
          );
        }
        return { ...need, abandonCount: 0 };
      }),
    };
  });

  const needOutcomes = world['needOutcomes'];
  if (!Array.isArray(needOutcomes)) {
    throw new Error('Save is corrupt: world.needOutcomes is missing or not an array');
  }
  const tallied: unknown[] = needOutcomes.map((row, index) => {
    if (!isRecord(row)) {
      throw new Error(`Save is corrupt: world.needOutcomes[${index}] is not an object`);
    }
    if (Object.keys(row).includes('abandoned')) {
      throw new Error(
        `world.needOutcomes[${index}] already has an "abandoned" field, so it is not a v8 row; migrating it would overwrite a real count`,
      );
    }
    return { ...row, abandoned: 0 };
  });

  return { ...world, guests: { ...guests, list: counted }, needOutcomes: tallied };
}

