/**
 * v15 -> v16: a world in which nothing counted how long the hotel left a need unserved (G-028a).
 *
 * ADR-0006 fires for the FIFTEENTH time. TWO changes, stated separately because their era
 * arguments are different even though both write a zero:
 *
 *   guests[].needs[].unservedTicks   ADDED, 0.   A v15 guest accumulated nothing because the
 *                                    quantity did not exist and no branch could write one. 0 is
 *                                    not a default standing in for missing information — it is
 *                                    the value the bytes support, because the v15 tick never
 *                                    wrote any other. `migrateV13ToV14`'s argument verbatim, one
 *                                    field down.
 *
 *   needOutcomes[].unservedTicks     ADDED, 0.   Same era argument, and the pair is added
 *   needOutcomes[].instanceTicks                 TOGETHER rather than one now and one later: the
 *                                    report divides one by the other, so a row carrying a
 *                                    numerator and no denominator would be a shape no arithmetic
 *                                    can read. 0/0 is "this era measured nothing", which is
 *                                    exactly true, and `assertNeedOutcomes`'s bound holds on it.
 *
 * THE DIRECTION IS STATED BECAUSE IT IS THE ONE THAT COULD MISLEAD. 0 is the most FLATTERING
 * value: a guest mid-stay when the save was taken resumes as though the hotel had never failed
 * it. The alternative — deriving a count from `arrivedTick` and the deficit — would be inventing
 * a history those bytes do not record, because nothing in them says what was or was not being
 * served. That is the drift ADR-0008 forbids, and it is the same call `migrateV13ToV14` made
 * about a mood.
 *
 * ---------------------------------------------------------------------------
 * AND THE WARRANT THAT MADE "FLATTERING" HARMLESS IS VOID SINCE G-028b. READ THIS BEFORE
 * REASONING ABOUT THIS DEFAULT.
 *
 * This block said: *"IT ALSO CANNOT CHANGE A LOADED WORLD'S BEHAVIOUR … nothing in
 * `packages/sim` reads any of these three fields."* **`unservedTicks` is read now** — by
 * `needBandOf`, through `reviewOf` and `metAtDeparture` (ADR-0037) — and **0 is not a neutral
 * value there, it is the value that scores the CEILING**: a need with no unserved ticks lands in
 * the top band, counts as `met`, and a guest whose whole vector reads 0 leaves the maximum
 * review whatever the hotel does for the rest of its stay.
 *
 * **SO THE FLATTERING DIRECTION IS NO LONGER AN UNDERSTATEMENT OF NEGLECT; IT IS AN INVENTED
 * HISTORY.** Every guest alive when a pre-G-028a save was written resumes with a clean slate and
 * departs with a perfect review. That is a different and worse hazard than the mixed
 * schema-3/schema-4 tally column `report.ts` concedes, and it is not the same finding.
 *
 * WHY THE DEFAULT DOES NOT MOVE ANYWAY, RE-ARGUED RATHER THAN INHERITED. The four candidates:
 *
 *   0 (SHIPPED)      invents a spotless history for a stay whose middle is unrecorded.
 *   the stay so far  invents the OPPOSITE history — that nothing was ever served — and is
 *                    equally unsupported by the bytes. It is not more honest for being harsher.
 *   refuse the save  invents nothing, and destroys every v15 save in existence to protect a
 *                    code path with no production caller.
 *   RECORD THE TICK  invents nothing either, and is the one that would actually work: store the
 *   THE COUNTER IS   tick the counter becomes valid from — `world.tick` is in the bytes at
 *   VALID FROM       migrate time — and grade a migrated guest over that window alone. **It
 *                    DECLINES to grade the unrecorded middle rather than asserting anything
 *                    about it**, which is exactly what ADR-0008 asks for.
 *
 * **SO "EVERY CANDIDATE INVENTS SOMETHING" IS TOO STRONG AND THE FOURTH IS THE COUNTER-EXAMPLE**
 * — it was missing from the first version of this list, which then leaned on that premise to say
 * ADR-0008 could not decide the question. It can, and it prefers the fourth.
 *
 * **THE TIEBREAK IS BLAST RADIUS AND THE FOURTH LOSES ON IT ANYWAY**: it is a new field on every
 * need of every guest, so it moves the save schema, the state hash, the measure golden and the
 * permanent fixture's migration chain — to protect a code path with no production caller. 0 is
 * kept because it is already in the shipped fixture and in every v16 save this repository has
 * written. **The conclusion and the tiebreak survive; the premise underneath them did not**, and
 * the fourth candidate is named here so that whichever goal gives `deserialise` a caller reaches
 * for it rather than re-deriving the list. `PARKING.md` carries it with the test that settles
 * whether the exposure is real.
 *
 * WHO IS EXPOSED: nothing today. `deserialise` has no production caller — the runner creates
 * every world it reports on and never loads a save, which is the same sentence that makes
 * `report.ts`'s review laws B and C safe. **The day something resumes a save, this is the field
 * that lies, and `PARKING.md` carries it with the test that settles it.**
 * ---------------------------------------------------------------------------
 *
 * THE OVERWRITE GUARDS ARE ONE PER FIELD and they are `Object.keys().includes` rather than
 * `in` — `JSON.parse` makes `__proto__` an own key (G-003). A v16 document fed in as v15 is
 * refused by them rather than silently zeroed, which is the one way this step could destroy data.
 *
 * NOT TESTED BY THE FIXTURE ALONE, AND HERE THAT IS MANDATORY RATHER THAN STYLISTIC: the
 * permanent v1 fixture carries an EMPTY guest list and an empty need tally, so both loops would
 * run over nothing and every assertion about them would pass while inspecting zero rows —
 * ADR-0007's exact shape. `needs.unserved.save.test.ts` drives a synthetic v15 world whose guests
 * carry full need vectors and whose tally carries distinct non-zero counters.
 */
function migrateV15ToV16(world: unknown): unknown {
  if (!isRecord(world)) {
    throw new Error('Save is corrupt: world is not an object');
  }
  const guests = world['guests'];
  if (!isRecord(guests)) {
    throw new Error('Save is corrupt: world.guests is missing, so its needs cannot gain a counter');
  }
  const list = guests['list'];
  if (!Array.isArray(list)) {
    throw new Error('Save is corrupt: world.guests.list is missing or not an array');
  }
  const migratedGuests: unknown[] = list.map((guest, index) => {
    if (!isRecord(guest)) {
      throw new Error(`Save is corrupt: world.guests.list[${index}] is not an object`);
    }
    const needs = guest['needs'];
    if (!Array.isArray(needs)) {
      throw new Error(
        `Save is corrupt: world.guests.list[${index}].needs is missing or not an array, so this guest has no needs to count against`,
      );
    }
    const migratedNeeds = needs.map((need, needIndex) => {
      if (!isRecord(need)) {
        throw new Error(`Save is corrupt: world.guests.list[${index}].needs[${needIndex}] is not an object`);
      }
      if (Object.keys(need).includes('unservedTicks')) {
        throw new Error(
          `world.guests.list[${index}].needs[${needIndex}] already has an "unservedTicks" field, so it is not a v15 ` +
            'need; migrating it would overwrite a real count',
        );
      }
      return { ...need, unservedTicks: 0 };
    });
    return { ...guest, needs: migratedNeeds };
  });

  const outcomes = world['needOutcomes'];
  if (!Array.isArray(outcomes)) {
    throw new Error('Save is corrupt: world.needOutcomes is missing or not an array');
  }
  const migratedOutcomes: unknown[] = outcomes.map((row, index) => {
    if (!isRecord(row)) {
      throw new Error(`Save is corrupt: world.needOutcomes[${index}] is not an object`);
    }
    for (const field of ['unservedTicks', 'instanceTicks']) {
      if (Object.keys(row).includes(field)) {
        throw new Error(
          `world.needOutcomes[${index}] already has a "${field}" field, so it is not a v15 tally row; migrating it ` +
            'would overwrite a real total',
        );
      }
    }
    return { ...row, unservedTicks: 0, instanceTicks: 0 };
  });

  return {
    ...world,
    guests: { ...guests, list: migratedGuests },
    needOutcomes: migratedOutcomes,
  };
}

/**
 * THE ROW A v16 WORLD WAS ON, FROZEN AT THE MOMENT v17 WAS DEFINED.
 *
 * A LITERAL, and it must stay one. `DEFAULT_MIN_ROW` in `grid.ts` holds the same `0` today
 * and `createGridBounds()` builds the same one-row plot; the two are ALLOWED to diverge
 * later and that divergence is correct rather than a bug to repair (ADR-0008 (1)).
 *
 * AND THIS ONE HAS A NAMED DAY. G-036 gives the player a verb that can draw into the
 * depth, and the shipped plot is widened on the day it does — `DEFAULT_MAX_ROW` stops being
 * 0. A migration that read the live constants would, on that day, start migrating the SAME
 * v16 bytes onto a DEEPER plot: every migrated room would gain free cells at row+1, and a
 * room that was `noDoor` when those bytes were written would come back VALID. That is not a
 * drifting counter, it is a migration REWRITING A VALIDITY VERDICT, which is why the freeze
 * here is worth more than the one-line deduplication it forbids.
 *
 * THE MIGRATED VALUE IS NOT INVENTED, AND IT HAS EXACTLY ONE HISTORICAL READING. A v16 world
 * WAS A STRIP: a floor had one row, because the coordinate system had no second horizontal
 * axis at all. So `minRow === maxRow` is not a default chosen for convenience, it is the
 * only statement those bytes support about their own plot — the `migrateV3ToV4` position
 * ("nothing is unknown here") rather than the `migrateV2ToV3` one ("invent nothing").
 *
 * The guard is structural, because the values coincide today and no assertion can tell the
 * implementations apart: the source scan in
 * `tools/headless/src/migration-scan.build.grid.provider.outcome.travel.save.test.ts`
 * forbids this file from naming `createGridBounds`, `DEFAULT_MIN_ROW` or `DEFAULT_MAX_ROW`
 * in executable code (ADR-0008 (3)).
 */
const V17_MIGRATION_ROW = 0;

/**
 * v16 -> v17: a world whose floors were strips rather than plans (G-034a, ADR-0046 §4.1).
 *
 * ADR-0006 fires for the SIXTEENTH time. `Cell` gains `row` and `GridBounds` gains
 * `minRow`/`maxRow`, so the permanent v1 fixture describes a world this build cannot load,
 * and the answer is this step. `fixtures/save-v1.ts` HAS A ZERO-LINE DIFF in this change;
 * the walk is 1 -> ... -> 16 -> 17.
 *
 * WHAT IT WRITES, AND WHY EVERY VALUE IS A FACT ABOUT THE BYTES RATHER THAN A CHOICE:
 *
 *   the plot          ->  `minRow: 0, maxRow: 0`. ONE ROW DEEP, because a v16 floor WAS one
 *                         row deep — the axis did not exist, so no v16 fact can contradict
 *                         this and none can support anything wider.
 *   every entity      ->  `at.row = 0` for a placed entity; an UNPLACED entity is left
 *                         exactly as it is. `at: null` is the state every entity carried out
 *                         of the v2 -> v3 chain, and a cell must not be invented for one now
 *                         for the reason that step gives at length.
 *   every guest       ->  `at.row = 0`, with no null branch: `Guest.at` is non-nullable by
 *                         construction since v11, so a guest without a cell is bytes no
 *                         migration produced and is refused rather than repaired.
 *
 * AND THE PROOF THAT IT INVENTS NOTHING IS A PROPERTY OF THE RULES, NOT AN ASSERTION ABOUT
 * INTENT: on a one-row plot the new 4-neighbour door rule DEGENERATES to the 2-neighbour
 * rule it replaces, because `cellFront`/`cellBack` of a cell at the only row are off the
 * plot and `isWithinBounds` skips them. So every migrated world keeps its EXACT validity
 * verdicts — same `noDoor`, same `unsupported`, same tallies. Any deeper migrated plot would
 * silently rewrite them, which is the case `V17_MIGRATION_ROW` is frozen against.
 *
 * Reads no content and no live constant, so the same v16 bytes produce the same v17 world
 * however the shipped plot changes afterwards (ADR-0008; see `V17_MIGRATION_ROW` for the
 * freeze and the scan that enforces it).
 *
 * NOT TESTED BY THE PERMANENT v1 FIXTURE, AND SAYING SO IS THE POINT. Every entity carried
 * out of `migrateV2ToV3` has `at: null` and the fixture's guest list is empty, so this step
 * walks the fixture with a ZERO-LINE DIFF while inspecting no cell at all — it would report
 * success having touched only `world.grid`. That is ADR-0007's exact shape, and it is the
 * paragraph `migrateV10ToV11` already carries one axis over. `grid.depth.save.test.ts`
 * drives a HAND-WRITTEN v16 world with placed entities, unplaced entities and guests through
 * every branch above, and asserts its validity tallies are UNCHANGED across 16 -> 17.
 */
function migrateV16ToV17(world: unknown): unknown {
  if (!isRecord(world)) {
    throw new Error('Save is corrupt: world is not an object');
  }
  const grid = world['grid'];
  if (!isRecord(grid)) {
    throw new Error('Save is corrupt: world.grid is missing, so its floors cannot be given a depth');
  }
  // The one way this step could destroy data — overwriting a plot somebody already gave a
  // depth — is the one thing it refuses to do, exactly as all fifteen earlier steps refuse.
  // `Object.keys().includes` rather than `in`, because `JSON.parse` makes `__proto__` an own
  // key (G-003).
  for (const edge of ['minRow', 'maxRow']) {
    if (Object.keys(grid).includes(edge)) {
      throw new Error(
        `world.grid already has a "${edge}" field, so it is not a v16 plot; migrating it would overwrite a real depth`,
      );
    }
  }

  const entities = world['entities'];
  if (!isRecord(entities)) {
    throw new Error('Save is corrupt: world.entities is missing, so its placements cannot be carried onto a plan');
  }
  const entityList = entities['list'];
  if (!Array.isArray(entityList)) {
    throw new Error('Save is corrupt: world.entities.list is missing or not an array');
  }
  const guests = world['guests'];
  if (!isRecord(guests)) {
    throw new Error('Save is corrupt: world.guests is missing, so its positions cannot be carried onto a plan');
  }
  const guestList = guests['list'];
  if (!Array.isArray(guestList)) {
    throw new Error('Save is corrupt: world.guests.list is missing or not an array');
  }

  /** The same refusal, one level down: a cell that already names a row is not a v16 cell. */
  const deepen = (at: Record<string, unknown>, where: string): Record<string, unknown> => {
    if (Object.keys(at).includes('row')) {
      throw new Error(
        `${where} already has a "row" field, so it is not a v16 cell; migrating it would overwrite a real position`,
      );
    }
    // Copied, never shared, and rebuilt rather than spread onto: `worldToJson` is an identity
    // cast, so two entities must not end up holding one cell object (`migrateV10ToV11`).
    return { ...at, row: V17_MIGRATION_ROW };
  };

  const migratedEntities: unknown[] = entityList.map((entity, index) => {
    if (!isRecord(entity)) {
      throw new Error(`Save is corrupt: world.entities.list[${index}] is not an object`);
    }
    const at = entity['at'];
    // UNPLACED STAYS UNPLACED. An entity that is nowhere has no cell to deepen, and giving
    // it one would invent the history `migrateV2ToV3` refused to invent.
    if (at === null) return { ...entity };
    if (!isRecord(at)) {
      throw new Error(
        `Save is corrupt: world.entities.list[${index}].at is neither null nor a cell, so it cannot be carried onto a plan`,
      );
    }
    return { ...entity, at: deepen(at, `world.entities.list[${index}].at`) };
  });

  const migratedGuests: unknown[] = guestList.map((guest, index) => {
    if (!isRecord(guest)) {
      throw new Error(`Save is corrupt: world.guests.list[${index}] is not an object`);
    }
    const at = guest['at'];
    // NO NULL BRANCH, and its absence is the rule rather than an omission: `Guest.at` has
    // been non-nullable since v11, so a guest standing nowhere is bytes no migration wrote.
    if (!isRecord(at)) {
      throw new Error(
        `Save is corrupt: world.guests.list[${index}].at is missing or not a cell, so it cannot be carried onto a plan`,
      );
    }
    return { ...guest, at: deepen(at, `world.guests.list[${index}].at`) };
  });

  return {
    ...world,
    grid: { ...grid, minRow: V17_MIGRATION_ROW, maxRow: V17_MIGRATION_ROW },
    entities: { ...entities, list: migratedEntities },
    guests: { ...guests, list: migratedGuests },
  };
}

